  local range = buffer(offset, length)
  local time_microseconds = range:uint()
  local value = jpx_nseequities_marketbyorder_flex_v1_3.timestamp.translate(time_microseconds, stored_time_seconds)
  local display = jpx_nseequities_marketbyorder_flex_v1_3.timestamp.display(time_microseconds, stored_time_seconds, packet)
  parent = parent:add(omi_jpx_nseequities_marketbyorder_flex_v1_3.fields.timestamp, range, value, display)

  jpx_nseequities_marketbyorder_flex_v1_3.time_seconds.generated(stored_time_seconds, range, packet, parent)

  display = jpx_nseequities_marketbyorder_flex_v1_3.time_microseconds.display(time_microseconds)
  parent:add(omi_jpx_nseequities_marketbyorder_flex_v1_3.fields.time_microseconds, range, time_microseconds, display)

  return offset + length, value
end

