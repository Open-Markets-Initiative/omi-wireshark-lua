  if jpx_nseequities_marketbyorder_flex_v1_3.format_timestamp then
    local stored_time_seconds = jpx_nseequities_marketbyorder_flex_v1_3.time_seconds.current

    if stored_time_seconds ~= nil then
      return jpx_nseequities_marketbyorder_flex_v1_3.timestamp.composite(buffer, offset, stored_time_seconds, packet, parent)
    end
  end

  return jpx_nseequities_marketbyorder_flex_v1_3.time_microseconds.dissect(buffer, offset, packet, parent)
end


