-- Dissector for Jpx NseEquities MarketByOrder Flex 1.3
function omi_jpx_nseequities_marketbyorder_flex_v1_3.dissector(buffer, packet, parent)
  -- Set protocol name
  packet.cols.protocol = omi_jpx_nseequities_marketbyorder_flex_v1_3.name

  if packet.port_type == 3 then
    -- Dissect protocol
    local protocol = parent:add(omi_jpx_nseequities_marketbyorder_flex_v1_3, buffer(), omi_jpx_nseequities_marketbyorder_flex_v1_3.description, "("..buffer:len().." Bytes)")
    return jpx_nseequities_marketbyorder_flex_v1_3.udp_packet.dissect(buffer, packet, protocol)
  end

  if packet.port_type == 2 then
    local length = buffer:len()
    local index = 0

    -- Dissect each message the segment carries
    while index < length do
      local remaining = length - index

      -- The message length lives in the header: wait for the header before reading it
      if remaining < jpx_nseequities_marketbyorder_flex_v1_3.tcp_packet_header.size then
        packet.desegment_offset = index
        packet.desegment_len = DESEGMENT_ONE_MORE_SEGMENT
        return length
      end

      local size = buffer(index, 2):uint() + 2
      -- A message split across segments: ask TCP for exactly the bytes still missing
      if remaining < size then
        packet.desegment_offset = index
        packet.desegment_len = size - remaining
        return length
      end

      local protocol = parent:add(omi_jpx_nseequities_marketbyorder_flex_v1_3, buffer(index, size), omi_jpx_nseequities_marketbyorder_flex_v1_3.description, "("..size.." Bytes)")
      jpx_nseequities_marketbyorder_flex_v1_3.tcp_packet.dissect(buffer(index, size):tvb(), packet, protocol)
      protocol:set_len(size)
      index = index + size
    end

    return index
  end
end


